import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import chalk from 'chalk';
import type { DiagnosticReport, DiagnosticEntry } from '../types.js';
import { createDiagnosticReport } from '../qnx/diagnostics.js';
import { logger } from '../utils/logger.js';

export interface PublishOptions {
  issueKey?: string;
  baseUrl?: string;
  email?: string;
  apiToken?: string;
  dryRun?: boolean;
  json?: boolean;
}

/**
 * Builds an Atlassian Document Format (ADF) comment representation
 * of the diagnostic report.
 */
function buildAdfComment(report: any, issueKey: string): any {
  const diagnostics: DiagnosticEntry[] = report.diagnostics || [];
  const errors =
    report.summary?.errors ??
    report.summary?.totalErrors ??
    diagnostics.filter((d: DiagnosticEntry) => d.severity === 'error').length;
  const warnings =
    report.summary?.warnings ??
    report.summary?.totalWarnings ??
    diagnostics.filter((d: DiagnosticEntry) => d.severity === 'warning').length;
  const total = report.summary?.total ?? (errors + warnings);
  const isSuccess = (report.buildStatus === 'success') || (errors === 0);

  const content: any[] = [
    {
      type: 'heading',
      attrs: { level: 3 },
      content: [
        {
          type: 'text',
          text: `ContextFlow QNX Build Diagnostics (${isSuccess ? 'SUCCESS' : 'FAILURE'})`,
        },
      ],
    },
    {
      type: 'paragraph',
      content: [
        { type: 'text', text: 'Build target: ', marks: [{ type: 'strong' }] },
        { type: 'text', text: `${report.target ?? 'x86_64'} (QNX SDP ${report.sdpVersion ?? '8.0'})` },
        { type: 'text', text: ' | Timestamp: ', marks: [{ type: 'strong' }] },
        { type: 'text', text: report.timestamp || new Date().toISOString() },
      ],
    },
    {
      type: 'paragraph',
      content: [
        {
          type: 'text',
          text: `Summary: ${errors} Error(s), ${warnings} Warning(s), ${total} Total Diagnostic Items.`,
          marks: [{ type: 'strong' }],
        },
      ],
    },
  ];

  if (diagnostics.length > 0) {
    const listItems = diagnostics.slice(0, 10).map((d: DiagnosticEntry) => {
      const loc = d.column ? `${d.file}:${d.line}:${d.column}` : `${d.file}:${d.line}`;
      const itemContent: any[] = [
        {
          type: 'paragraph',
          content: [
            {
              type: 'text',
              text: `[${d.severity.toUpperCase()}] `,
              marks: [{ type: 'strong' }],
            },
            {
              type: 'text',
              text: `${loc} - ${d.message} `,
            },
          ],
        },
      ];

      if (d.suggestion) {
        itemContent.push({
          type: 'paragraph',
          content: [
            {
              type: 'text',
              text: `Recommended Action: ${d.suggestion}`,
              marks: [{ type: 'em' }],
            },
          ],
        });
      }

      return {
        type: 'listItem',
        content: itemContent,
      };
    });

    content.push({
      type: 'bulletList',
      content: listItems,
    });
  }

  content.push({
    type: 'paragraph',
    content: [
      {
        type: 'text',
        text: 'Report generated by ContextFlow QNX Companion. Open the ContextFlow Diagnostics panel on this issue for Rovo AI explanations and documentation suggestions.',
        marks: [{ type: 'subsup', attrs: { type: 'sub' } }],
      },
    ],
  });

  return {
    version: 1,
    type: 'doc',
    content,
  };
}

export async function runPublish(
  reportPath: string,
  options: PublishOptions = {},
): Promise<{ success: boolean; commentId?: string; dryRun: boolean }> {
  const issueKey = options.issueKey ?? process.env['JIRA_ISSUE_KEY'];
  const baseUrl = options.baseUrl ?? process.env['JIRA_BASE_URL'];
  const email = options.email ?? process.env['JIRA_EMAIL'];
  const apiToken = options.apiToken ?? process.env['JIRA_API_TOKEN'];

  if (!issueKey) {
    throw new Error('Target Jira issue key is required. Specify --issue-key <KEY> or set JIRA_ISSUE_KEY.');
  }

  // Read report or log
  let rawContent = '';
  if (reportPath === '-' || (!reportPath && !process.stdin.isTTY)) {
    const chunks: Buffer[] = [];
    for await (const chunk of process.stdin) {
      chunks.push(typeof chunk === 'string' ? Buffer.from(chunk) : chunk);
    }
    rawContent = Buffer.concat(chunks).toString('utf-8');
  } else {
    rawContent = await readFile(resolve(reportPath), 'utf-8');
  }

  let report: any;
  const trimmed = rawContent.trim();
  if (trimmed.startsWith('{')) {
    report = JSON.parse(trimmed);
  } else {
    // Automatically parse raw build log into structured diagnostic report
    logger.info(`Parsing raw compiler log from ${reportPath}...`);
    report = createDiagnosticReport(rawContent, {
      project: reportPath,
      target: 'x86_64',
      rawLog: rawContent,
    });
  }

  const adfPayload = buildAdfComment(report, issueKey);

  // If dry-run requested or credentials missing
  if (options.dryRun || !baseUrl || !email || !apiToken) {
    if (!options.dryRun) {
      logger.warn('Jira credentials (JIRA_BASE_URL, JIRA_EMAIL, JIRA_API_TOKEN) not detected.');
      logger.info('Simulating Jira publication (--dry-run mode).');
    }

    console.log('\n' + chalk.bold.cyan(`[DRY-RUN] Jira Comment Payload for Issue: ${chalk.yellow(issueKey)}`));
    console.log(chalk.dim('Atlassian Document Format (ADF) output:'));
    console.log(JSON.stringify(adfPayload, null, 2));
    console.log(
      chalk.green(`\n[OK] Dry-run complete. Would publish to: ${baseUrl || 'https://your-domain.atlassian.net'}/browse/${issueKey}\n`),
    );

    return {
      success: true,
      dryRun: true,
    };
  }

  // Real REST API Publication
  const cleanBase = baseUrl.replace(/\/+$/, '');
  const apiUrl = `${cleanBase}/rest/api/3/issue/${encodeURIComponent(issueKey)}/comment`;
  const authHeader = 'Basic ' + Buffer.from(`${email}:${apiToken}`).toString('base64');

  logger.info(`Publishing diagnostics to Jira issue ${issueKey} at ${apiUrl}...`);

  const response = await fetch(apiUrl, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: authHeader,
      Accept: 'application/json',
    },
    body: JSON.stringify({ body: adfPayload }),
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Jira API returned error ${response.status} (${response.statusText}): ${errorText}`);
  }

  const result: any = await response.json();
  logger.success(`Successfully published diagnostic comment to ${issueKey} (Comment ID: ${result.id})`);

  // Also publish raw JSON report to Jira Issue Properties for Forge App panel
  try {
    const propUrl = `${cleanBase}/rest/api/3/issue/${encodeURIComponent(issueKey)}/properties/contextflow_diagnostics`;
    const propResponse = await fetch(propUrl, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        Authorization: authHeader,
      },
      body: JSON.stringify(report),
    });
    if (propResponse.ok) {
      logger.success(`Stored structured diagnostic data in Jira issue property for Forge panel`);
    }
  } catch (propErr: any) {
    logger.warn(`Could not sync issue property: ${propErr.message}`);
  }

  return {
    success: true,
    commentId: result.id,
    dryRun: false,
  };
}
